#!/usr/bin/env bun
/**
 * Compile the bus to a real single binary, dashboard included.
 *
 * The awkward part is the dashboard: `bun build --compile` can only embed
 * imports it can *see*, and the dashboard is a directory of content-hashed
 * filenames that do not exist until Vite has run. So this generates a module
 * with one static `import … with { type: "file" }` per built asset, compiles
 * against it, and puts the stub back. A dynamic import of a computed path —
 * the obvious approach — survives `bun run` and silently breaks under
 * `--compile`, which is the failure this whole dance exists to avoid.
 *
 *   bun scripts/build-binary.ts                    the host platform
 *   bun scripts/build-binary.ts --all              every supported target
 *   bun scripts/build-binary.ts --target bun-linux-x64
 *
 * The other awkward part is SQLite. bql.sh's driver loads libsqlite3 at runtime
 * and looks for the vendored build relative to its own source, which a compiled
 * binary does not have on disk; it would fall back to whatever the system has,
 * which on Linux may be nothing at all and is never the pinned build. So the
 * host target embeds the library `sqlite:build` produces and points
 * `BQL_SQLITE_LIB` at it, the same library bql.sh's own image ships beside its
 * source. Only the host target: the library is compiled for the machine that
 * builds it. A cross-compiled binary carries no library and needs
 * `BQL_SQLITE_LIB` or a system libsqlite3 where it runs. The assignment rides
 * in the dashboard manifest because that is the one generated module the bus
 * imports, so it covers `bql bus …`; `bql serve` in the same binary does not
 * import the bus and still searches the usual way.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";

const argv = process.argv.slice(2);
const has = (name: string) => argv.includes(`--${name}`);
const flag = (name: string, fallback?: string) => {
  const index = argv.indexOf(`--${name}`);
  return index < 0 ? fallback : (argv[index + 1] ?? fallback);
};

const TARGETS = [
  "bun-linux-x64",
  "bun-linux-arm64",
  "bun-darwin-arm64",
  "bun-darwin-x64",
] as const;

const root = resolve(import.meta.dir, "..");
const generated = `${root}/src/dashboard/embedded.generated.ts`;
const dashboard = `${root}/dist/dashboard`;
const outDir = `${root}/dist/bin`;

const stub = await readFile(generated, "utf8");

async function run(command: string[], label: string) {
  const child = Bun.spawn(command, { cwd: root, stdout: "inherit", stderr: "inherit" });
  if ((await child.exited) !== 0) throw new Error(`${label} failed`);
}

/** Every file under `dist/dashboard`, as paths the server will be asked for. */
async function assets(directory: string, prefix = ""): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory())
      out.push(...(await assets(`${directory}/${entry.name}`, `${prefix}/${entry.name}`)));
    else out.push(`${prefix}/${entry.name}`);
  }
  return out;
}

/** Builds the pinned libsqlite3 for this machine if it is missing, and returns its path. */
async function hostLibrary(): Promise<string> {
  const child = Bun.spawn(
    ["bun", "run", `${root}/../db/scripts/sqlite.ts`, "--quiet"],
    { cwd: root, stdout: "pipe", stderr: "inherit" },
  );
  const out = await new Response(child.stdout).text();
  if ((await child.exited) !== 0) throw new Error("sqlite:build failed");
  return out.trim().split("\n").pop() as string;
}

async function writeManifest(sqliteLibrary: string | null) {
  const files = await assets(dashboard);
  const imports: string[] = [];
  const entries: string[] = [];
  if (sqliteLibrary) {
    imports.push(
      `import sqliteLibrary from ${JSON.stringify(relative(dirname(generated), sqliteLibrary))} with { type: "file" };`,
      "// The embedded libsqlite3, loaded before anything opens a database. An explicit BQL_SQLITE_LIB still wins.",
      "process.env.BQL_SQLITE_LIB ??= sqliteLibrary;",
    );
  }
  files.forEach((file, index) => {
    const name = `asset${index}`;
    imports.push(
      `import ${name} from "../../dist/dashboard${file}" with { type: "file" };`,
    );
    entries.push(`  ${JSON.stringify(file)}: ${name},`);
  });
  await writeFile(
    generated,
    `// Generated by scripts/build-binary.ts. Do not edit; see the stub in git.\n${imports.join(
      "\n",
    )}\n\nexport const EMBEDDED_ASSETS: Record<string, string> = {\n${entries.join(
      "\n",
    )}\n};\n`,
  );
  return files.length;
}

try {
  if (!(await Bun.file(`${dashboard}/index.html`).exists()))
    await run(["bun", "run", "build"], "bun run build");

  await mkdir(outDir, { recursive: true });

  const host = `bun-${process.platform === "darwin" ? "darwin" : "linux"}-${process.arch === "arm64" ? "arm64" : "x64"}`;
  const targets = has("all") ? [...TARGETS] : [flag("target") ?? host];
  const library = targets.includes(host) ? await hostLibrary() : null;

  for (const target of targets) {
    const embedded = await writeManifest(target === host ? library : null);
    console.log(
      `${target}: embedding ${embedded} dashboard files${
        target === host ? ` and ${library}` : ", no libsqlite3 (not the host target)"
      }`,
    );
    const outfile = `${outDir}/bql-${target.replace(/^bun-/, "")}`;
    await run(
      [
        "bun",
        "build",
        "--compile",
        `--target=${target}`,
        "../db/src/cli.ts",
        "--outfile",
        outfile,
      ],
      `compile ${target}`,
    );
    const size = Bun.file(outfile).size;
    console.log(`${outfile}  ${(size / 1024 / 1024).toFixed(1)} MiB`);
  }

  // Checksums, so a release asset can be verified without trusting the page it
  // was downloaded from.
  const lines: string[] = [];
  for (const entry of await readdir(outDir)) {
    if (entry.endsWith(".sha256") || entry === "checksums.txt") continue;
    const bytes = await Bun.file(`${outDir}/${entry}`).arrayBuffer();
    const digest = new Bun.CryptoHasher("sha256")
      .update(new Uint8Array(bytes))
      .digest("hex");
    lines.push(`${digest}  ${entry}`);
  }
  await writeFile(`${outDir}/checksums.txt`, `${lines.join("\n")}\n`);
  console.log(`\n${outDir}/checksums.txt`);
} finally {
  // Always restore the stub, including after a failure: leaving the generated
  // manifest behind would make the next `bun run` from source import files
  // that may not be there.
  await writeFile(generated, stub);
}
